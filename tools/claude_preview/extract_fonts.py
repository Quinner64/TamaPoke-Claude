#!/usr/bin/env python3
"""Copy the U8g2 fonts the Claude dashboard uses out of U8g2's u8g2_fonts.c.

The full u8g2_fonts.c is ~40 MB; compiling it for the PC preview is slow and
pointless when the dashboard uses a handful of fonts. This finds every
`u8g2_font_*` name in the given sources and writes:

  <out>/fonts.c    the font arrays, byte for byte as in U8g2
  <out>/U8g2lib.h  a stand-in for U8g2lib.h that only declares those arrays

Usage:
  python3 tools/claude_preview/extract_fonts.py U8G2_FONTS_C OUT_DIR SOURCE...
"""

import re
import sys
from pathlib import Path

NAME_RE = re.compile(r"\bu8g2_font_[A-Za-z0-9_]+\b")


def wanted_fonts(sources):
    names = set()
    for src in sources:
        names.update(NAME_RE.findall(Path(src).read_text(encoding="utf-8")))
    return sorted(names)


def extract(fonts_c, names):
    text = Path(fonts_c).read_text(encoding="latin-1")
    out = {}
    for name in names:
        m = re.search(r"const uint8_t " + re.escape(name) + r"\[\d+\][^=]*=\s*\n(.*?);\n", text, re.S)
        if not m:
            raise SystemExit(f"font {name} not found in {fonts_c}")
        out[name] = m.group(0)
    return out


def main(argv):
    if len(argv) < 4:
        print(__doc__)
        return 2
    fonts_c, out_dir, sources = argv[1], Path(argv[2]), argv[3:]
    names = wanted_fonts(sources)
    arrays = extract(fonts_c, names)
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "fonts.c", "w", encoding="latin-1") as f:
        f.write("// Generated by extract_fonts.py from U8g2 (BSD-2-Clause). Do not edit.\n")
        f.write("#include <stdint.h>\n#define U8G2_FONT_SECTION(name)\n\n")
        for name in names:
            f.write(arrays[name] + "\n")
    with open(out_dir / "U8g2lib.h", "w", encoding="utf-8") as f:
        f.write("// PC stand-in for U8g2lib.h: only the font arrays (see extract_fonts.py).\n")
        f.write("#pragma once\n#include <stdint.h>\n#define U8G2_FONT_SECTION(name)\n")
        f.write('#ifdef __cplusplus\nextern "C" {\n#endif\n')
        for name in names:
            f.write(f"extern const uint8_t {name}[];\n")
        f.write("#ifdef __cplusplus\n}\n#endif\n")
    print(f"{len(names)} fonts -> {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
